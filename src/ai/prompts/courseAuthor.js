const CATEGORY_TOPIC_HINT = {
  basics: 'основы трейдинга для полных новичков',
  forex: 'рынок Forex: валютные пары, пипсы, спреды, торговые сессии',
  crypto: 'криптовалютный рынок: биржи, кошельки, волатильность, основные монеты',
  technical_analysis: 'технический анализ: паттерны, индикаторы, уровни поддержки/сопротивления',
  fundamental_analysis: 'фундаментальный анализ: новости, макроэкономика, отчёты компаний',
  psychology: 'психология трейдинга: дисциплина, эмоции, управление стрессом',
  risk_management: 'управление рисками: размер позиции, стоп-лосс, диверсификация',
  ai_trading: 'использование AI и алгоритмов в трейдинге',
};

export function buildCourseOutlinePrompt({ category, lessonCount = 5, existingLessonTitles = [] }) {
  const topicHint = CATEGORY_TOPIC_HINT[category] || category;

  const continuationNote = existingLessonTitles.length
    ? `\n\nВАЖНО: В курсе уже есть уроки на темы:\n${existingLessonTitles.map((t, i) => `${i + 1}. ${t}`).join('\n')}\n\nПридумай ${lessonCount} НОВЫХ уроков, которые логично ПРОДОЛЖАЮТ курс дальше (более глубокие/смежные темы), НЕ повторяя то, что уже перечислено выше.`
    : '';

  return `Ты методист образовательной платформы по трейдингу. Придумай структуру курса на тему: "${topicHint}".${continuationNote}

Верни ТОЛЬКО валидный JSON (без markdown-разметки, без \`\`\`, без пояснений до или после) в точности такой структуры:
{
  "title": "Название курса на русском (коротко, привлекательно)",
  "description": "Описание курса на русском, 1-2 предложения",
  "lessons": [
    { "title": "Название урока 1", "summary": "О чём этот урок, 1 предложение" }
  ]
}

Требования:
- Ровно ${lessonCount} уроков в массиве "lessons".
- Уроки идут от простого к сложному, логично продолжая друг друга.
- Названия уроков конкретные и понятные новичку, без воды.
- Это образовательный контент, не финансовые советы.`;
}

export function buildLessonContentPrompt({ courseTitle, lessonTitle, lessonSummary, lessonNumber, totalLessons }) {
  return `Ты опытный преподаватель трейдинга, пишешь текст урока для Telegram-бота.

Курс: "${courseTitle}"
Урок ${lessonNumber} из ${totalLessons}: "${lessonTitle}"
Суть урока: ${lessonSummary}

Напиши полный текст урока на русском языке:
- Объём: 200-400 слов.
- Простой, дружелюбный язык для новичка, с примерами из жизни.
- Структура: короткое введение → основная часть с конкретными пояснениями → короткий вывод.
- Используй эмодзи для акцентов вместо markdown-разметки.
- НИКОГДА не используй markdown-таблицы (|---|---|), "**", "#" — только чистый текст с эмодзи и переносами строк.
- Если уместно — заверши мыслью, которая мотивирует перейти к следующему уроку.
- В конце ОБЯЗАТЕЛЬНО добавь отдельной строкой: "⚠️ Материал носит образовательный характер и не является финансовой рекомендацией."

Верни ТОЛЬКО текст урока, без заголовков вида "Урок X:" в начале.`;
}

export function buildQuizGenerationPrompt({ lessonTitle, lessonContent }) {
  return `На основе этого урока составь ОДИН проверочный вопрос с 3 вариантами ответа (только один верный).

Урок: "${lessonTitle}"
Текст урока:
"""
${lessonContent}
"""

Верни ТОЛЬКО валидный JSON (без markdown, без пояснений) в точности такой структуры:
{
  "question": "Текст вопроса на русском",
  "options": ["Вариант A", "Вариант B", "Вариант C"],
  "correctIndex": 0
}

Вопрос должен проверять понимание ключевой идеи урока, а не мелкую деталь.`;
}

export default { buildCourseOutlinePrompt, buildLessonContentPrompt, buildQuizGenerationPrompt };
